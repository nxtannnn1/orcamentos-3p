const preWriteCodes = new Set([
  "CORRECTION_NOT_APPLIED", "GRAPH_WRITE_INVALID_PAYLOAD", "GRAPH_WRITE_AUTHENTICATION_FAILED",
  "GRAPH_WRITE_THROTTLED", "GRAPH_WRITE_PREPARATION_FAILED", "GRAPH_WRITE_PERMISSION_UNVERIFIED",
  "INVALID_CORRECTION", "VERSION_REQUIRED", "CORRECTIONS_NOT_CONFIGURED", "CORRECTION_CONFLICT", "CORRECTION_STATE_CLOSED",
  "CORRECTION_EMPTY", "CORRECTION_SCHEMA_REQUIRED", "CORRECTION_MATERIAL_INVALID", "BUDGET_CLOSED", "CORRECTION_OPERATION_CONFLICT",
  "PERSON_RESOLUTION_NOT_CONFIGURED", "PERSON_RESOLUTION_UNAVAILABLE", "PERSON_NOT_FOUND", "PERSON_AMBIGUOUS", "PERSON_IDENTITY_MISMATCH", "DECISION_TENANT_MISMATCH",
  "CORRECTION_PENDING", "GRAPH_PERMISSION_TOO_BROAD", "GRAPH_WRITE_FORBIDDEN", "ITEM_NOT_FOUND", "DECISION_CONFLICT",
]);
export class CorrectionRequestError extends Error {
  readonly requiresReconciliation: boolean;
  constructor(message: string, readonly code = "CORRECTION_UNCONFIRMED") {
    super(message); this.name = "CorrectionRequestError";
    this.requiresReconciliation = !preWriteCodes.has(code);
  }
}
